"""git 钩子的脚本侧:`nomess git-hook <钩子名>`(git 在提交那一刻调用)、`nomess hooks install | uninstall | status`、`nomess refresh`。
钩子里的顺序(设计稿 ② / ③):读索引快照 → 先定启不启用 → 满足条件时在内存里算生成结果、叠成候选树 → 对候选树检查 → 有红退出 1 →
无红才把候选树里的同样字节和模式写进索引、再写工作区(apply:检查什么就提交什么)。检查读快照(没暂存的草稿不影响);
cmd 规则和 cmd / py 生成器在工作区里跑、读磁盘,钩子里 cmd / py 生成段不刷新。
装钩子:启动器 <git 公共目录>/nomess-hook(不进版本库,写着本机 Python 和插件脚本的绝对路径)+ 钩子目录里的 pre-commit、pre-merge-commit 各调一次启动器。
已有别人的钩子不覆盖,按管理器打出接线配方:husky(用户脚本 .husky/<钩子名>,不碰 .husky/_)、pre-commit 框架(.pre-commit-config.yaml 里两个本地 hook)、其余手写 sh。
接入状态按接入方式查(status):原生看钩子文件,husky 看用户脚本,框架看配置里两个 id。hooksPath 是相对路径时每个 worktree 各自解析(doctor 逐个查);
钩子文件只调 $(git rev-parse --git-common-dir)/nomess-hook,不写本仓库路径,所以全局绝对 hooksPath 下也安全。
uninstall 只删内容和自己写的一致的钩子文件,启动器换成一行 exit 0 的存根(存根 = 主动卸载的记录,guard 不再催装,hooks install 恢复)。"""
import os
import re
import subprocess
import sys

import check
import docgen
import nm_config
import outwrite
import snapshot
import map as nm_map
import rules as nm_rules
from messages import t

HOOKS = ("pre-commit", "pre-merge-commit")
LAUNCHER = "nomess-hook"
SELF = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "nomess.py")).replace("\\", "/")
def gen_dirs(cfg):
    """只这两个目录归 nomess 所有;其余的写入都是带 GEN 段的宿主文件。系统图目录跟着 docs_root。"""
    return (nm_map.out_dir(cfg) + "/", nm_rules.RULES_DIR + "/")

HOOK_BODY = '''#!/bin/sh
h="$(git rev-parse --git-common-dir)/%s"
if [ -f "$h" ]; then sh "$h" %s || exit $?; fi
'''
LAUNCHER_BODY = '''#!/bin/sh
# nomess git hook launcher, written by `nomess hooks install`; not tracked by git
py='%s'
nm='%s'
if [ ! -f "$nm" ] || ! "$py" -c "import sys" >/dev/null 2>&1; then
  echo "nomess: plugin script or Python not found, this commit was not checked (run nomess hooks install)" >&2
  exit 0
fi
exec "$py" "$nm" git-hook "$@"
'''
STUB_BODY = '''#!/bin/sh
# nomess git hook launcher: switched off by `nomess hooks uninstall` (run `nomess hooks install` to switch it on again)
exit 0
'''
RECIPE = '''h="$(git rev-parse --git-common-dir)/%s"
if [ -f "$h" ]; then sh "$h" %s || exit $?; fi'''
FRAMEWORK_IDS = {"pre-commit": "nomess", "pre-merge-commit": "nomess-merge"}
FRAMEWORK_MARK = "generated by pre-commit"  # pre-commit 框架写的钩子文件里有这句
FRAMEWORK_ENTRY = "sh -c 'h=\"$(git rev-parse --git-common-dir)/%s\"; if [ -f \"$h\" ]; then exec sh \"$h\" %s; fi'"


def _git(root, *args):
    p = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return p.returncode, p.stdout.strip(), p.stderr.strip()


def _sq(path):
    return path.replace("'", "'\\''")


# ---------------------------------------------------------------- 刷新计划

def plan(snap, cfg, exec_):
    """内存里算出全部生成结果 {路径: 新内容 bytes | None(删)}:docgen 生成段 + 系统图 + 规则文件。cmd / py 生成器只在 exec_ 时跑。"""
    _, puts = docgen.run(snap, cfg, exec_=exec_)
    return {**puts, **nm_map.plan(snap, cfg), **nm_rules.plan(snap, cfg)}


def _prune(root, cfg):
    for d in gen_dirs(cfg):
        outwrite.prune_empty(root, d)


def main_refresh(argv):
    """nomess refresh:docgen + map + rules 一次写完。"""
    config = nm_config.find_config()
    root = os.path.dirname(config)
    cfg = nm_config.load(config)
    with snapshot.open_snapshot(root, "worktree") as snap:
        changes = plan(snap, cfg, True)
    outwrite.apply(root, changes)
    _prune(root, cfg)
    for rel in changes:
        print("%s %s" % (t("WRITTEN"), rel))
    return 0


# ---------------------------------------------------------------- 钩子

def _skip_reasons(root, idx, rels, cfg):
    """{生成物: 不能安全改写的原因},可以改写的不列:设了 working-tree-encoding / filter(宿主和输出目录都查,一次 check-attr --stdin);
    宿主文件另查:不是普通文件、工作区内容和索引不一致(hash-object --path 套用该路径的换行和过滤规则再比 oid,
    autocrlf 下干净的 CRLF 文件不算改动;不依赖 assume-unchanged)。"""
    if not rels:
        return {}
    p = subprocess.run(["git", "check-attr", "-z", "--stdin", "working-tree-encoding", "filter"], cwd=root, capture_output=True,
                       input="".join(r + "\0" for r in rels).encode("utf-8", "surrogateescape"))
    tok = p.stdout.split(b"\0")
    blocked = {tok[i].decode("utf-8", "surrogateescape") for i in range(0, len(tok) - 2, 3) if tok[i + 2] not in (b"unspecified", b"unset")}
    out = {}
    for rel in rels:
        if rel in blocked:
            out[rel] = t("GH_SKIP_ATTR")
            continue
        if rel.startswith(gen_dirs(cfg)):
            continue
        if idx.files().get(rel) not in snapshot.REGULAR:
            out[rel] = t("GH_SKIP_NOTREG")
            continue
        work = subprocess.run(["git", "hash-object", "--path=" + rel, "--", os.path.join(root, rel)], cwd=root, capture_output=True, text=True)
        index = subprocess.run(["git", "hash-object", "--no-filters", "--stdin"], cwd=root, input=idx.read(rel), capture_output=True, text=False)
        if work.returncode or work.stdout.strip() != index.stdout.decode().strip():
            out[rel] = t("GH_SKIP_DIRTY")
    return out


def _refreshes(root, name, cfg, idx):
    """③ 的四条:pre-commit;在 main_branch 上;索引和 HEAD 有差别或正在收尾合并;GIT_INDEX_FILE 的文件名是 index 或 index.lock。"""
    if name != "pre-commit" or _git(root, "branch", "--show-current")[1] != cfg["main_branch"]:
        return False
    if os.path.basename(os.environ.get("GIT_INDEX_FILE", "index")) not in ("index", "index.lock"):
        return False
    return bool(idx.changed()) or _git(root, "rev-parse", "-q", "--verify", "MERGE_HEAD")[0] == 0


def main_git_hook(argv):
    name = argv[0] if argv else ""
    if name not in HOOKS:
        raise ValueError("nomess git-hook: unknown hook %r (expected %s)" % (name, " | ".join(HOOKS)))
    root = snapshot.toplevel(os.getcwd())
    hsnap = snapshot.open_snapshot(root, "tree", "HEAD") if snapshot.has_commit(root, "HEAD") else None
    try:
        return _gate(root, name, hsnap)
    finally:
        if hsnap:
            hsnap.close()


def _gate(root, name, hsnap):
    """钩子的检查段:hsnap 是 HEAD 的树(没有提交为 None)。"""
    head = hsnap.text(nm_config.CONFIG_NAME) if hsnap else None
    with snapshot.open_snapshot(root, "index") as idx:
        text = idx.text(nm_config.CONFIG_NAME)
        if text is None and head is None:
            return 0  # 没启用
        if text is None:  # HEAD 有、待提交里删了:放宽(B2),照样挡
            nm_config.parse(head, nm_config.CONFIG_NAME)  # 只为按项目语言出提示
            print(t("GH_B2", nm_config.CONFIG_NAME), file=sys.stderr)
            return 1
        cfg = nm_config.parse(text, nm_config.CONFIG_NAME)
        snap, notes, changes = idx, [], {}
        if _refreshes(root, name, cfg, idx):
            changes = plan(idx, cfg, False)
            skip = _skip_reasons(root, idx, [r for r, data in changes.items() if data is not None], cfg)
            for rel in [r for r in changes if r in skip]:
                del changes[rel]
                notes.append(t("GH_SKIPPED", rel, skip[rel]))
            if changes:
                snap = idx.overlay(changes)
        res = check.evaluate(snap, hsnap, exec_cmd=True, gate=True)  # 有效配置和 HEAD 不同时它自己全树重判
        reds = [f for f in res["findings"] if f["level"] == "red"]
        notes += [f["msg"] for f in res["findings"] if f["rule"] == "CMD1"]
        index_only = {}
        if res["writes"] and not reds:  # 基线跟着改名走:和生成物同一条路写进这次提交
            skip = _skip_reasons(root, idx, list(res["writes"]), cfg)
            for rel, data in res["writes"].items():
                if rel in skip:  # 工作区有未暂存编辑或设了过滤 / 编码:只写索引,不碰工作区那份
                    index_only[rel] = data
                    notes.append(t("GH_BASE_INDEX", rel, skip[rel]))
                else:
                    changes[rel] = data
            snap = snap.overlay(res["writes"])
        for n in notes:
            print(n, file=sys.stderr)
        if reds:
            f = reds[0]
            print(t("GH_RED", len(reds), f["file"], f["line"], f["rule"], f["msg"]), file=sys.stderr)
            print(t("GH_RED_NOTE"), file=sys.stderr)
            if name == "pre-merge-commit":
                print(t("GH_RED_MERGE"), file=sys.stderr)
            return 1
        try:
            if changes:
                outwrite.apply(root, changes, snap)
                _prune(root, cfg)
            if index_only:
                outwrite.apply(root, index_only, snap, index_only=True)
        except snapshot.SnapshotError as e:
            print(t("GH_ADD_FAIL", e), file=sys.stderr)
            return 1
    return 0


# ---------------------------------------------------------------- 安装

def hook_dir(root):
    p = _git(root, "rev-parse", "--git-path", "hooks")[1]
    return p if os.path.isabs(p) else os.path.join(root, p)


def launcher_path(root):
    p = _git(root, "rev-parse", "--git-common-dir")[1]
    return os.path.join(p if os.path.isabs(p) else os.path.join(root, p), LAUNCHER)


def _read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return None


def manager(root):
    """钩子是谁管的:husky(core.hooksPath 指向 .husky/_)| framework(钩子目录里的文件是 pre-commit 框架写的)| native。"""
    d = hook_dir(root).replace("\\", "/")
    if d.endswith("/.husky/_"):
        return "husky"
    if any(FRAMEWORK_MARK in (_read(os.path.join(d, h)) or "") for h in HOOKS):
        return "framework"
    return "native"


def _hook_state(root, mgr, h):
    """wired | noexec | other | missing。
    native:钩子文件里调了启动器 = wired(Unix 上没有执行位 = noexec,git 不跑它);有别人的钩子、没接 = other;没有 = missing。
    husky:用户脚本 .husky/<钩子名> 里有启动器的调用(husky 自己的 .husky/_ 不看)。
    framework:.pre-commit-config.yaml 里有这个阶段的 id、钩子文件是框架写的。"""
    if mgr == "husky":
        body = _read(os.path.join(os.path.dirname(hook_dir(root)), h))
        return "missing" if body is None else "wired" if LAUNCHER in body else "other"
    p = os.path.join(hook_dir(root), h)
    body = _read(p)
    if mgr == "framework":
        cfg = _read(os.path.join(root, ".pre-commit-config.yaml")) or ""
        mine = re.search(r"^\s*-?\s*id:\s*%s\s*$" % FRAMEWORK_IDS[h], cfg, re.M) and FRAMEWORK_MARK in (body or "")
        return "wired" if mine else "missing" if body is None else "other"
    return ("missing" if body is None else "other" if LAUNCHER not in body
            else "wired" if os.name == "nt" or os.access(p, os.X_OK) else "noexec")


def status(root):
    """{launcher: 启动器路径, launcher_ok: 启动器存在, stub: 启动器是 uninstall 留下的存根(主动停用), current: 启动器里的插件路径就是当前插件,
    manager: native | husky | framework, hook_dir: 实际钩子目录, hooks: {钩子名: wired | noexec | other | missing}}。"""
    lp = launcher_path(root)
    body = _read(lp)
    m = re.search(r"^nm='(.*)'$", body or "", re.M)
    mgr = manager(root)
    return {"launcher": lp, "launcher_ok": body is not None, "stub": body == STUB_BODY,
            "current": bool(m) and m.group(1).replace("'\\''", "'") == SELF, "manager": mgr, "hook_dir": hook_dir(root),
            "hooks": {h: _hook_state(root, mgr, h) for h in HOOKS}}


def write_launcher(root):
    py = sys.executable.replace("\\", "/")
    nm_config.atomic_write(launcher_path(root), LAUNCHER_BODY % (_sq(py), _sq(SELF)))


def install(root):
    """装启动器和两个钩子;返回 [(钩子名, 结果)],结果 installed | kept | other。别人的钩子不覆盖;
    husky 和 pre-commit 框架管着钩子,什么都不写进钩子目录,只返回现在接没接(kept | other),配方由 main_hooks 打出。"""
    write_launcher(root)
    mgr = manager(root)
    if mgr != "native":
        return [(h, "kept" if _hook_state(root, mgr, h) == "wired" else "other") for h in HOOKS]
    d = hook_dir(root)
    os.makedirs(d, exist_ok=True)
    out = []
    for h in HOOKS:
        p = os.path.join(d, h)
        old = _read(p)
        if old is None or old == HOOK_BODY % (LAUNCHER, h):  # 自己写的:重写并补执行位
            nm_config.atomic_write(p, HOOK_BODY % (LAUNCHER, h))
            os.chmod(p, 0o755)
            out.append((h, "installed"))
        else:
            out.append((h, "kept" if LAUNCHER in old else "other"))
    return out


def uninstall(root):
    """删内容和自己写的一致的钩子文件(别人的、husky 和框架的不碰),启动器换成存根。"""
    d = hook_dir(root)
    for h in HOOKS:
        p = os.path.join(d, h)
        if _read(p) == HOOK_BODY % (LAUNCHER, h):
            os.remove(p)
    nm_config.atomic_write(launcher_path(root), STUB_BODY)


def relative_hooks_path(root):
    """core.hooksPath 设了相对路径(如 husky 的 .husky/_):每个 worktree 按自己的根解析,各自要接。"""
    v = _git(root, "config", "core.hooksPath")[1]
    return bool(v) and not os.path.isabs(v) and not v.startswith("~")


def worktrees(root):
    """这个仓库所有 worktree 的目录(含 root 自己)。"""
    return [l[len("worktree "):] for l in _git(root, "worktree", "list", "--porcelain")[1].splitlines() if l.startswith("worktree ")]


def recipe(mgr, h):
    """别人管着的钩子 h 要加的接线配方(文字)。"""
    if mgr == "husky":
        return t("GH_RECIPE_HUSKY", h) + "\n" + RECIPE % (LAUNCHER, h)
    if mgr == "framework":
        hooks = "".join("    - id: %s\n      name: nomess\n      language: system\n      pass_filenames: false\n      always_run: true\n"
                        "      stages: [%s]\n      entry: %s\n" % (FRAMEWORK_IDS[x], x, FRAMEWORK_ENTRY % (LAUNCHER, x)) for x in HOOKS)
        return t("GH_RECIPE_FRAMEWORK") + "\n- repo: local\n  hooks:\n" + hooks + "pre-commit install --hook-type pre-commit --hook-type pre-merge-commit"
    return RECIPE % (LAUNCHER, h)


def main_hooks(argv):
    import argparse
    ap = argparse.ArgumentParser(prog="nomess hooks", description="install / remove / show the git hook gate")
    ap.add_argument("action", choices=("install", "uninstall", "status"))
    a = ap.parse_args(argv)
    root = snapshot.toplevel(os.getcwd())
    try:
        nm_config.load(nm_config.find_config())  # 提示语的语言
    except (FileNotFoundError, ValueError):
        pass
    if a.action == "install":
        mgr, shown = manager(root), False
        for h, res in install(root):
            print(t("GH_INST_" + res.upper(), h))
            if res == "other" and not (mgr == "framework" and shown):  # 框架配方一次写全两个阶段
                print(recipe(mgr, h))
                shown = True
                if h == "pre-merge-commit" and mgr == "native":
                    print(t("GH_MERGE_ORDER"))
    elif a.action == "uninstall":
        uninstall(root)
        print(t("GH_UNINSTALLED"))
    else:
        st = status(root)
        print(t("GH_STATUS", st["launcher"].replace("\\", "/"), t("GH_STUB") if st["stub"] else t("GH_YES") if st["launcher_ok"] else t("GH_NO"),
                st["manager"], str(st["hook_dir"]).replace("\\", "/"), ", ".join("%s=%s" % kv for kv in st["hooks"].items())))
    return 0
